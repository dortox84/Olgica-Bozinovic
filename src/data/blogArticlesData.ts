export function getArticleBySlug(slug: string): Article | undefined {
  return BLOG_ARTICLES_DATA.find((a) => a.slug === slug || a.id === slug);
}

export function getAllArticles(): Article[] {
  return BLOG_ARTICLES_DATA;
}

export function getRelatedArticles(currentSlug: string, count: number = 3): Article[] {
  const current = getArticleBySlug(currentSlug);
  if (!current) return BLOG_ARTICLES_DATA.slice(0, count);

  if (current.related_slugs && current.related_slugs.length > 0) {
    const related = current.related_slugs
      .map((s) => getArticleBySlug(s))
      .filter((a): a is Article => !!a);
    if (related.length >= count) return related.slice(0, count);
  }

  return BLOG_ARTICLES_DATA.filter((a) => a.slug !== current.slug).slice(0, count);
}
